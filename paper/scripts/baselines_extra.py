"""Adds the "no pointer movement" rule to the same-data
comparison table for the Sensors manuscript:

    .venv/bin/python paper/scripts/baselines_extra.py

Reads the released feature table only. Both rules, step_cv = 0 and
step_mean = 0 (fewer than two pointer moves), are scored on the ten session-wise
splits, the kind-stratified folds (4 folds x 10 seeds), and leave-one-kind-out
with the genuine test partition of the first split. The step_cv row must
reproduce the one that baselines.py wrote into baselines.tex; the new row is
then inserted below it, and the result is written to baselines_sensors.tex.
"""
from __future__ import annotations

import os
import re
import sys

import numpy as np
import pandas as pd
from sklearn.metrics import f1_score, roc_auc_score
from sklearn.model_selection import GroupShuffleSplit

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import review2 as r2  # noqa: E402

ra, ml = r2.ra, r2.ra.ml
TABLES = r2.TABLES
CSV = os.path.join(r2.KEYSPARK, "data", "keyspark_windows.csv")


def rule_row(X, y, g, kind, flag) -> dict:
    gss_f1, gss_auc = [], []
    splits = list(GroupShuffleSplit(n_splits=10, test_size=0.25, random_state=ra.SEED).split(X, y, groups=g))
    for _, te in splits:
        gss_f1.append(f1_score(y[te], flag[te]))
        gss_auc.append(roc_auc_score(y[te], flag[te]))
    st_f1, st_auc = [], []
    for r in range(ra.N_REPEATS):
        fold = ra.stratified_folds(y, g, kind, np.random.default_rng(ra.SEED + r), 4)
        for f in range(4):
            te = fold == f
            st_f1.append(f1_score(y[te], flag[te]))
            st_auc.append(roc_auc_score(y[te], flag[te]))
    te_mask = np.zeros(len(y), dtype=bool)
    te_mask[splits[0][1]] = True
    loko = [f1_score(y[(te_mask & (y == 0)) | (kind == k)], flag[(te_mask & (y == 0)) | (kind == k)], zero_division=0)
            for k in ra.KINDS]
    return {"gss": (np.mean(gss_f1), np.std(gss_f1), np.mean(gss_auc)),
            "strat": (np.mean(st_f1), np.std(st_f1), np.mean(st_auc)), "loko": float(np.mean(loko))}


def fmt(name: str, r: dict) -> str:
    g, s = r["gss"], r["strat"]
    return (f"{name} & Rule & {g[0]:.3f} $\\pm$ {g[1]:.3f} & {g[2]:.4f} & "
            f"{s[0]:.3f} $\\pm$ {s[1]:.3f} & {s[2]:.4f} & {r['loko']:.3f} \\\\")


def main() -> None:
    df = pd.read_csv(CSV)
    data = df[df["set"] != "injected"].reset_index(drop=True)
    X, y, g = data[ml.FEATURES].values, data["label"].values, data["session"].values
    kind = data["kind"].fillna("").values
    stepcv = rule_row(X, y, g, kind, (data["step_cv"].values == 0).astype(int))
    nomove = rule_row(X, y, g, kind, (data["step_mean"].values == 0).astype(int))
    src = open(os.path.join(TABLES, "baselines.tex")).read()
    m = re.search(r"^.*step\\_cv.* & Rule & .*$", src, re.M)
    assert m, "step_cv rule row not found in baselines.tex"
    expect = fmt("X", stepcv).split(" & ", 1)[1]
    assert m.group(0).split(" & ", 1)[1].strip() == expect.strip(), (m.group(0), expect)
    row = fmt("No pointer movement", nomove)
    out = src[:m.end()] + "\n" + row + src[m.end():]
    out = out.replace("% generated by paper/scripts/baselines.py -- do not edit by hand",
                      "% generated by paper/scripts/baselines_extra.py from baselines.tex -- do not edit by hand")
    out = out.replace("Rules learn nothing; their AUC is that of a binary score.",
                      "Rules learn nothing; their AUC is that of a binary score. The no-movement rule flags windows "
                      "without measurable pointer movement (\\texttt{step\\_mean} $= 0$).")
    with open(os.path.join(TABLES, "baselines_sensors.tex"), "w") as fh:
        fh.write(out)
    print("step_cv rule reproduced;", row)


if __name__ == "__main__":
    main()
