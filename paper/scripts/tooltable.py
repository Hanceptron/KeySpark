"""Render the documented behaviour of real keep-active tools (collected by
slowtools.py into paper/tables/slowtools.json) as a LaTeX table, so the
manuscript's tool-versus-generator comparison is generated, not typed.

    .venv/bin/python paper/scripts/tooltable.py
"""

import json
import os

SRC = "paper/tables/slowtools.json"
OUT = "paper/tables/tools.tex"

# Short, paper-facing wording for each documented tool. The facts come from the
# JSON (interval, event types, source); only the phrasing is fixed here.
ROWS = {
    "Mouse Jiggler (arkane-systems)": {
        "name": "Mouse Jiggler", "os": "Windows",
        "events": r"pointer \texttt{move}",
        "geometry": r"relative $(+4,+4)$, then $(-4,-4)$",
        "random": "optional random timer",
        "cite": "mousejiggler",
        "generator": r"\texttt{jiggler}: 1--8\,s",
    },
    "Caffeine (Zhorn Software)": {
        "name": "Caffeine", "os": "Windows",
        "events": r"F15 \texttt{key\_up}",
        "geometry": "none",
        "random": "none",
        "cite": "caffeine",
        "generator": r"\texttt{keep\_awake}: 6--12\,s, \texttt{key\_down}",
    },
    "Jiggler (Stick Software)": {
        "name": "Jiggler", "os": "macOS",
        "events": r"burst of 35 \texttt{move}",
        "geometry": "random, within 14 px",
        "random": "fixed period",
        "cite": "jigglermac",
        "generator": "not modelled",
    },
    "KeepingYouAwake / caffeinate (macOS)": {
        "name": "KeepingYouAwake", "os": "macOS",
        "events": "none (power assertion)",
        "geometry": "none",
        "random": "n/a",
        "cite": "keepingyouawake",
        "generator": "invisible by construction",
    },
}


def main() -> None:
    with open(SRC) as fh:
        tools = json.load(fh)["tools_documented"]
    lines = [
        "% generated by paper/scripts/tooltable.py -- do not edit by hand",
        r"\begin{table}[t]",
        r"\caption{Default behaviour of real keep-active tools, read from their "
        r"documentation or source code, against the generator kind that stands "
        r"for them in training.}",
        r"\label{tab:tools}",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{llrllll}",
        r"\toprule",
        r"Tool & Platform & Period & Events & Movement & Timing & Generator kind (period, events) \\",
        r"\midrule",
    ]
    for t in tools:
        r = ROWS.get(t["tool"])
        if r is None:
            continue
        period = t.get("default_interval_s")
        period_s = "--" if period is None else rf"{period}\,s"
        lines.append(
            rf"{r['name']}~\cite{{{r['cite']}}} & {r['os']} & {period_s} & "
            rf"{r['events']} & {r['geometry']} & {r['random']} & {r['generator']} \\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\\[2pt] \footnotesize Period is the documented default; the macOS "
        r"Jiggler waits for that much idle time before each burst. The generator "
        r"kinds run about 5 to 60 times faster than these defaults so that a one-minute "
        r"window holds at least five events. KeepingYouAwake holds a power assertion and "
        r"emits no input. Movement is the default pattern in the tool's source code. The generator's auto-typer and auto-clicker kinds are not modelled "
        r"on a documented tool.",
        r"\end{table}",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  wrote {OUT}")


if __name__ == "__main__":
    main()
