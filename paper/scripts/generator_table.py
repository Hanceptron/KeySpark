"""Generator settings table for the Sensors manuscript, read from keyspark.botgen
so the description of the synthetic class is generated, not typed.

    .venv/bin/python paper/scripts/generator_table.py

Writes paper/tables/generator.tex (label tab:generator). Session lengths come
from botgen.synthetic_event_frame() with its defaults, the call that produced
the 16 training sessions; window counts come from the released feature table.
"""
from __future__ import annotations

import os
import sys

import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, REPO)
from keyspark import botgen  # noqa: E402

CSV = os.path.join(REPO, "data", "keyspark_windows.csv")
OUT = os.path.join(REPO, "paper", "tables", "generator.tex")


def main() -> None:
    syn = botgen.synthetic_event_frame().sort_values("ts")
    syn["s"] = (syn["ts"].diff().fillna(0) > 1800).cumsum()
    dur = syn.groupby("s")["ts"].agg(lambda t: (t.max() - t.min()) / 60).values
    win = pd.read_csv(CSV)
    win = win[win["set"] == "synthetic"].groupby("kind").size()
    per = len(dur) // len(botgen.KINDS)

    def rng(a, b, unit="s"):
        return f"{a:g}--{b:g}\\,{unit}"

    shape = {"normal": "diagonal", "linear": "horizontal", "circle": "octagon"}
    pats = ", ".join(f"{shape.get(name, name)} ({len(steps)} steps, at most "
                     f"{max(max(abs(dx), abs(dy)) for dx, dy in steps)}\\,px per axis)"
                     for name, steps in botgen._MOVE_PATTERNS.items())
    keyname = {"scroll_lock": "Scroll Lock"}
    what = {
        "jiggler": f"pointer \\texttt{{move}} walking one fixed pattern per session: {pats}, scaled by 1 to 3",
        "typer": f"\\texttt{{key\\_down}} over {len(botgen._TYPER_KEYS)} keys "
                 f"({', '.join(botgen._TYPER_KEYS)})",
        "keep_awake": "\\texttt{key\\_down} of one key per session ("
                      + ", ".join(keyname.get(k, k.upper()) for k in botgen._KEEPAWAKE_KEYS) + ")",
        "clicker": "left \\texttt{click} at the current pointer position",
    }
    rows = []
    for i, k in enumerate(botgen.KINDS):
        d = dur[i * per:(i + 1) * per]
        lo, hi = botgen._BASE_RANGE[k]
        rows.append(f"\\texttt{{{k.replace('_', chr(92) + '_')}}} & {rng(lo, hi)} & {what[k]} & "
                    f"{d.min():.0f}--{d.max():.0f} & {int(win.get(k, 0))} \\\\")
    j0, j1 = botgen._JITTER_RANGE
    notes = (
        f"Four sessions per kind. Per session the generator draws the base interval between events from the range shown, "
        f"a timing jitter of {100 * j0:.0f}\\% to {100 * j1:.0f}\\% of it, and the pattern, distance, or key. "
        f"Each session holds as many events as its base interval gives in 30 minutes; 10\\% of intervals "
        f"are lengthened by 3 to 12 base intervals as pauses, which stretches a session to the length shown. "
        f"{100 * botgen.CONTAMINATION:.0f}\\% of events are drawn from another kind (cross-modal "
        f"contamination). No kind emits \\texttt{{key\\_up}} or \\texttt{{scroll}}. Windows are the one-minute "
        f"windows with at least five events."
    )
    lines = [
        "% generated by paper/scripts/generator_table.py -- do not edit by hand",
        r"\begin{table}[H]",
        r"\caption{Settings of the synthetic automation generator.}",
        r"\label{tab:generator}",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{lrp{6.6cm}rr}",
        r"\toprule",
        r"Kind & Interval & Events & Minutes & Windows \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}",
        rf"\\[2pt] \footnotesize {notes}",
        r"\end{table}",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
