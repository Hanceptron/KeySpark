"""Calendar of day-level decisions, replotted from the released feature table
(Sensors manuscript):

    .venv/bin/python paper/scripts/calendar_plot.py

Days are UTC calendar days of the released table (day 1 = 21 May 2026). Shading
is the number of scored genuine windows that day. Genuine days that the released
configuration (tau = 0.8, m >= 2, out-of-fold scores) flags are outlined in red;
automation days are filled red when detected and hatched when missed. Writes
paper/figures/calendar.tex (label fig:calendar).
"""
from __future__ import annotations

import datetime as dt
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import review2 as r2  # noqa: E402

ra = r2.ra
CSV = os.path.join(r2.KEYSPARK, "data", "keyspark_windows.csv")
OUT = os.path.join(os.path.dirname(HERE), "figures", "calendar.tex")
DAY1 = dt.date(2026, 5, 21)


def main() -> None:
    df = pd.read_csv(CSV)
    data = df[df["set"] != "injected"].reset_index(drop=True)
    X, y, g = data[ra.ml.FEATURES].values, data["label"].values, data["session"].values
    scored = ra.released_scores(df, data, X, y, g)
    st = ra.day_stats(scored, ra.TAU)
    st["flag"] = st["count"] >= ra.MIN_WINDOWS
    st["date"] = st["day"].map(lambda d: DAY1 + dt.timedelta(days=int(d) - 1))
    gen = st[st["set"] == "genuine"].set_index("date")
    inj = st[st["set"] == "injected"].set_index("date")
    windows = df[df["set"] == "genuine"].groupby("day").size()
    windows.index = [DAY1 + dt.timedelta(days=int(d) - 1) for d in windows.index]
    wmax = int(windows.max())

    first = min(inj.index.min(), gen.index.min())
    first = first - dt.timedelta(days=first.weekday())
    last = gen.index.max()
    last = last + dt.timedelta(days=6 - last.weekday())
    weeks = (last - first).days // 7 + 1
    cw, ch = 1.0, 0.52
    lines = [
        "% generated by paper/scripts/calendar_plot.py -- do not edit by hand",
        r"\begin{figure}[H]",
        r"\centering",
        r"\begin{tikzpicture}[font=\scriptsize]",
    ]
    for i, name in enumerate(["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]):
        lines.append(rf"\node[anchor=east] at (-0.1,{-i * ch:.2f}) {{{name}}};")
    for w in range(weeks):
        monday = first + dt.timedelta(days=7 * w)
        lines.append(rf"\node at ({w * cw + cw / 2:.2f},{ch * 0.9:.2f}) {{{monday.day} {monday.strftime('%b')}}};")
        for i in range(7):
            d = monday + dt.timedelta(days=i)
            x0, y0 = w * cw + 0.04, -i * ch - ch / 2 + 0.03
            x1, y1 = (w + 1) * cw - 0.04, -i * ch + ch / 2 - 0.03
            shade = int(round(8 + 47 * windows.get(d, 0) / wmax)) if d in windows.index else 0
            fill = f"black!{shade}" if shade else "white"
            style = [f"fill={fill}", "draw=black!25"]
            if d in gen.index and gen.loc[d, "flag"]:
                style = [f"fill={fill}", "draw=red!80!black", "line width=1.1pt"]
            if d in inj.index:
                style = (["fill=red!70", "draw=red!80!black"] if inj.loc[d, "flag"]
                         else [f"fill={fill}", "draw=red!80!black", "line width=1.1pt", "pattern=north east lines", "pattern color=red!70"])
            lines.append(rf"\draw[{', '.join(style)}] ({x0:.2f},{y0:.2f}) rectangle ({x1:.2f},{y1:.2f});")
            color = "white" if (d in inj.index and inj.loc[d, "flag"]) or shade > 40 else "black"
            hatched = d in inj.index and not inj.loc[d, "flag"]
            box = ", fill=white, inner sep=1pt" if hatched else ""
            lines.append(rf"\node[text={color}{box}] at ({(x0 + x1) / 2:.2f},{(y0 + y1) / 2:.2f}) {{{d.day}}};")
    flagged = [d for d in gen.index if gen.loc[d, "flag"]]
    det = [d for d in inj.index if inj.loc[d, "flag"]]
    miss = [d for d in inj.index if not inj.loc[d, "flag"]]
    fmt = lambda ds: ", ".join(f"{d.day} {d.strftime('%B')}" for d in sorted(ds))
    lines += [
        r"\end{tikzpicture}",
        (r"\caption{Day-level decisions of the released configuration ($\tau = 0.8$, $m \geq 2$), "
         r"replotted from the released feature table in the layout of the dashboard's history calendar. "
         rf"Days are UTC calendar days from {first.day} {first.strftime('%B')} to {last.day} {last.strftime('%B')} {last.year}; grey shading gives the number of scored "
         rf"genuine windows that day (darkest {wmax:,}). Genuine windows are scored out of fold. Red fill: "
         rf"automation days detected ({fmt(det)}); red hatching: the test user's day, not detected ({fmt(miss)}), "
         rf"which also holds genuine activity; red outline: genuine days flagged ({fmt(flagged)}).}}"),
        r"\label{fig:calendar}",
        r"\end{figure}",
    ]
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", OUT, "flagged", flagged, "detected", det, "missed", miss, "max windows", wmax)


if __name__ == "__main__":
    main()
