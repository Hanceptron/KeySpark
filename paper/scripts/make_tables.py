def load_genuine() -> pd.DataFrame:
    """The genuine human corpus: archive, frozen, with seeded automation removed."""
    df = events_io.load_events()
    df = events_io.exclude_nonhuman(df)
    df["day"] = pd.to_datetime(df["event_time"]).dt.date
    return df[df["day"] <= FREEZE].sort_values("event_time").reset_index(drop=True)


def add_sessions(df: pd.DataFrame, tag: str) -> pd.DataFrame:
    """Label each event with a session id using the batch layer's 300 s idle gap.

    Session ids are what the grouped split holds out. Windows inside one session
    are strongly correlated - the same typing burst, the same synthetic cadence -
    so splitting on windows leaks, and splitting on sessions does not.
    """
    # _prepare derives event_time from epoch ts when absent, so real archive
    # frames and generated frames normalise through exactly the same path.
    out = ml._prepare(df).sort_values(["user", "event_time"])
    gap = out.groupby("user")["event_time"].diff().dt.total_seconds()
    new = gap.isna() | (gap > SESSION_GAP_S)
    out["session"] = tag + ":" + new.cumsum().astype(str)
    return out


def windows_with_sessions(events: pd.DataFrame, tag: str) -> pd.DataFrame:
    """Featurize, then attach the session each window belongs to."""
    ev = add_sessions(events, tag)
    feats = ml._window_features(ev)
    ev["window_start"] = ev["event_time"].dt.floor("min")
    owner = (
        ev.groupby(["user", "window_start"])["session"].first().reset_index()
    )
    return feats.merge(owner, on=["user", "window_start"], how="left")


def labeled_dataset() -> pd.DataFrame:
    """Human (0) and synthetic automation (1) windows, each carrying a session id."""
    human = windows_with_sessions(load_genuine(), "H")
    human["label"] = 0
    synth = windows_with_sessions(botgen.synthetic_event_frame(), "B")
    synth["label"] = 1
    return pd.concat([human, synth], ignore_index=True)


