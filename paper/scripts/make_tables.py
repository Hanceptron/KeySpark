def write_roc_figure(roc_data: dict) -> None:
    """Per-fold ROC curves for the leave-one-kind-out evaluation, on a
    logarithmic false-positive axis so near-perfect curves stay separable."""
    styles = {
        "jiggler": "solid, color=blue, thick",
        "typer": "dashed, color=red, thick",
        "keep_awake": "dotted, color=teal, very thick",
        "clicker": "dashdotted, color=orange, thick",
    }
    plots = []
    for kind, (fpr, tpr, auc) in roc_data.items():
        fpr = np.clip(fpr, 1e-3, None)  # log axis cannot show fpr = 0
        coords = " ".join(f"({f:.4g},{t:.4g})" for f, t in zip(fpr, tpr))
        legend = kind.replace("_", r"\_")
        plots.append(
            rf"\addplot[{styles[kind]}] coordinates {{{coords}}};" "\n"
            rf"\addlegendentry{{\texttt{{{legend}}} (AUC {auc:.4f})}}"
        )
    body = rf"""% generated by paper/scripts/make_tables.py -- do not edit by hand
\begin{{figure}}[t]
\centering
\begin{{tikzpicture}}
\begin{{axis}}[
  width=0.78\columnwidth, height=5.4cm, scale only axis,
  xmode=log, xmin=0.001, xmax=1, ymin=0, ymax=1.02,
  xlabel={{False-positive rate (log)}}, ylabel={{True-positive rate}},
  grid=major, legend pos=south east, legend cell align=left,
  legend style={{font=\footnotesize}},
]
{chr(10).join(plots)}
\end{{axis}}
\end{{tikzpicture}}
\caption{{ROC curves of the leave-one-kind-out folds of
Table~\ref{{tab:crosskind}}, on a logarithmic false-positive axis
(false-positive rates of zero are clipped to $10^{{-3}}$). Every fold ranks
the classes almost perfectly, including the \texttt{{typer}} fold whose
$F_1$ at the fixed threshold is zero: the failure is calibration, not
separability.}}
\label{{fig:roc}}
\end{{figure}}
"""
    path = os.path.join("paper/figures", "roc_crosskind.tex")
    with open(path, "w") as fh:
        fh.write(body)
    print(f"  wrote {path}")


def oof_probabilities(df: pd.DataFrame, n_splits: int = 5) -> pd.DataFrame:
    """Out-of-fold automation probability for every human window.

    Folds are cut on sessions, so a window is always scored by a forest that
    trained on none of its own session. Returns one row per (user,
    window_start) for the label-0 rows only, which is what the day-level policy
    needs to report an honest false-alarm rate.
    """
    X, y, g = df[ml.FEATURES].values, df["label"].values, df["session"].values
    proba = np.zeros(len(df))
    folds = GroupKFold(n_splits=n_splits)
    for tr, te in folds.split(X, y, groups=g):
        model = ml._make_model()
        model.fit(X[tr], y[tr])
        proba[te] = model.predict_proba(X[te])[:, 1]
    out = df[["user", "window_start", "label"]].copy()
    out["proba"] = proba
    return out[out["label"] == 0][["user", "window_start", "proba"]]


def write_performance_tables(numbers: dict) -> None:
    """Turn benchmark.json into Table IV and the micro-batch sweep.

    Skipped with a warning if the benchmark has not been run, so the table
    generator never invents a performance figure.
    """
    path = os.path.join(OUT_DIR, "benchmark.json")
    if not os.path.exists(path):
        print("  benchmark.json missing -- run benchmark.py first; skipping")
        return
    with open(path) as fh:
        bench = json.load(fh)
    numbers["benchmark"] = bench

    def mean(section: str, field: str):
        return bench.get(section, {}).get("summary", {}).get(field, {}).get("mean")

    def std(section: str, field: str):
        return bench.get(section, {}).get("summary", {}).get(field, {}).get("std")

    # Table I: the machine every number above was measured on.
    env = bench.get("environment", {})
    write_table(
        "environment", "Evaluation environment.", "tab:environment", "ll",
        ["Component", "Version"],
        [
            ["Processor", f"{esc(env.get('cpu', '?'))}, {env.get('cores', '?')} cores"],
            ["Memory", f"{env.get('memory_gb', '?')} GB"],
            ["Operating system", f"macOS {env.get('os', '?').split()[-1]}"],
            ["Java runtime", "OpenJDK 21.0.11 LTS"],
            ["Apache Spark", f"{env.get('pyspark', '?')} (Scala 2.13.17)"],
            ["Apache Kafka", "3.8.1, KRaft, single broker"],
            ["Python", env.get("python", "?")],
            ["scikit-learn", env.get("scikit_learn", "?")],
        ],
        notes=r"Spark runs in \texttt{local[*]} mode; Kafka runs in a container.",
    )

    rows = []
    if "batch" in bench:
        rows.append([
            "Batch analytics (full archive)",
            f"{fmt(mean('batch', 'throughput_events_per_sec'))} ev/s",
            f"$\\pm$ {fmt(std('batch', 'throughput_events_per_sec'))}",
        ])
    if "streaming" in bench:
        rows.append([
            "Structured Streaming replay",
            f"{fmt(mean('streaming', 'processed_rows_per_sec'))} rows/s",
            f"$\\pm$ {fmt(std('streaming', 'processed_rows_per_sec'))}",
        ])
        rows.append([
            "Micro-batch latency (mean)",
            f"{fmt(mean('streaming', 'mean_batch_latency_ms'))} ms",
            f"$\\pm$ {fmt(std('streaming', 'mean_batch_latency_ms'), 1)}",
        ])
        rows.append([
            "Micro-batch latency (max)",
            f"{fmt(mean('streaming', 'max_batch_latency_ms'))} ms",
            f"$\\pm$ {fmt(std('streaming', 'max_batch_latency_ms'))}",
        ])

    # End-to-end latency is a design floor, not an engine limit: a per-minute
    # metric cannot exist until its minute has passed.
    rows += [
        [r"\midrule Window duration", "60 s", "by design"],
        ["Watermark", "5 s", "by design"],
        ["Metrics trigger interval", "0--30 s", "scheduling"],
        [r"\textbf{End-to-end floor}", r"\textbf{65 s}", "sum of the above"],
    ]
    n_events = mean("streaming", "events") or mean("batch", "events")
    write_table(
        "performance",
        "Processing performance over three repetitions.", "tab:performance",
        "lrr", ["Measure", "Value", "Variation"], rows,
        notes=rf"Measured over the complete {fmt(n_events)}-event archive. "
              r"Streaming throughput is \emph{processed} rows per second "
              r"(input rows divided by Spark's \texttt{triggerExecution} time) "
              r"at four files per micro-batch.",
    )

    if "sweep" in bench:
        sweep_rows = []
        for entry in bench["sweep"]:
            s, r = entry["summary"], entry["runs"][0]
            sweep_rows.append([
                str(r["max_files_per_trigger"]),
                fmt(r["micro_batches"]),
                fmt(s["processed_rows_per_sec"]["mean"]),
                fmt(s["mean_batch_latency_ms"]["mean"]),
                fmt(s["max_batch_latency_ms"]["mean"]),
            ])
        write_table(
            "sweep",
            "Streaming throughput against micro-batch size.", "tab:sweep",
            "rrrrr",
            ["Files/batch", "Batches", "Rows/s", "Mean ms", "Max ms"],
            sweep_rows,
            notes="Throughput scales with micro-batch size while per-batch "
                  "latency stays near constant, showing that a fixed per-batch "
                  "cost, not row processing, sets the rate at small batch sizes.",
        )
        write_sweep_figure(bench)


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    numbers: dict = {}
    print("Loading corpus...")

    genuine = load_genuine()
    data = labeled_dataset()
    human = data[data.label == 0]
    synth = data[data.label == 1]

    # -- Table II: dataset composition -------------------------------------
    ev = add_sessions(genuine, "H")
    n_sessions = ev["session"].nunique()
    durs = ev.groupby("session")["event_time"].agg(
        lambda s: (s.max() - s.min()).total_seconds() / 60
    )
    counts = genuine["type"].value_counts()
    kd = genuine[genuine["type"] == "key_down"]
    words = int(kd["key"].isin([" ", "Key.space"]).sum())
    corrections = int(kd["key"].isin(["Key.backspace", "Key.delete"]).sum())
    minute_counts = genuine.groupby(
        pd.to_datetime(genuine["event_time"]).dt.floor("min")
    ).size()

    numbers["dataset"] = {
        "events": int(len(genuine)),
        "days": int(genuine["day"].nunique()),
        "first_day": str(genuine["day"].min()),
        "last_day": str(genuine["day"].max()),
        "sessions": int(n_sessions),
        "active_hours": float(durs.sum() / 60),
        "median_session_min": float(durs.median()),
        "windows_total": int(len(minute_counts)),
        "windows_scoreable": int((minute_counts >= ml.MIN_WINDOW_EVENTS).sum()),
        "windows_dropped": int((minute_counts < ml.MIN_WINDOW_EVENTS).sum()),
        "keystrokes": int(len(kd)),
        "distinct_keys": int(kd["key"].nunique()),
        "words": words,
        "corrections": corrections,
        "correction_rate": corrections / max(len(kd), 1),
        "by_type": {k: int(v) for k, v in counts.items()},
    }

    rows = [
        ["Events", fmt(len(genuine))],
        ["Active days", fmt(genuine["day"].nunique())],
        ["Collection span", f"{genuine['day'].min()} to {genuine['day'].max()}"],
        ["Sessions (5-min idle gap)", fmt(n_sessions)],
        ["Active time (hours)", fmt(durs.sum() / 60, 1)],
        ["Median session (minutes)", fmt(durs.median(), 1)],
        [r"\midrule One-minute windows", fmt(len(minute_counts))],
        [r"\quad scored ($\geq 5$ events)",
         fmt((minute_counts >= ml.MIN_WINDOW_EVENTS).sum())],
        [r"\quad abstained ($< 5$ events)",
         fmt((minute_counts < ml.MIN_WINDOW_EVENTS).sum())],
    ]
    for t in ["scroll", "move", "key_down", "key_up", "click"]:
        if t in counts:
            rows.append([rf"\midrule \texttt{{{esc(t)}}} events"
                         if t == "scroll" else rf"\texttt{{{esc(t)}}} events",
                         f"{fmt(counts[t])} ({counts[t] / len(genuine) * 100:.1f}\\%)"])
    rows += [
        [r"\midrule Distinct keys", fmt(kd["key"].nunique())],
        ["Word boundaries (space)", fmt(words)],
        ["Corrections (backspace/delete)",
         f"{fmt(corrections)} ({corrections / max(len(kd), 1) * 100:.1f}\\%)"],
    ]
    write_table(
        "dataset", "Genuine corpus after the data freeze.", "tab:dataset",
        "lr", ["Quantity", "Value"], rows,
        notes="Seeded demonstration days and the test user are excluded, "
              "as in the released code.",
    )

    # -- Table V: window-level results, both splits -------------------------
    print("Evaluating window-level classification...")
    numbers["class_balance"] = {
        "human": int(len(human)), "non_human": int(len(synth)),
        "human_sessions": int(human["session"].nunique()),
        "non_human_sessions": int(synth["session"].nunique()),
    }

    r_rand = evaluate(data, ml._make_model(), ml.FEATURES, grouped=False)
    rep = evaluate_repeated(data, lambda: ml._make_model(), ml.FEATURES)
    numbers["splits"] = {
        "Random (window-wise)": r_rand,
        "Grouped (session-wise)": rep,
    }
    # Transposed (metrics as rows) so the mean +- std cells fit the column.
    split_rows = [
        ["Accuracy", f"{r_rand['accuracy']:.3f}", fmt_pm(rep["accuracy"])],
        ["Precision", f"{r_rand['precision']:.3f}", fmt_pm(rep["precision"])],
        ["Recall", f"{r_rand['recall']:.3f}", fmt_pm(rep["recall"])],
        [r"$F_1$", f"{r_rand['f1']:.3f}", fmt_pm(rep["f1"])],
        ["ROC-AUC", f"{r_rand['roc_auc']:.4f}", fmt_pm(rep["roc_auc"], 4)],
    ]
    first = rep["first"]
    write_table(
        "splits",
        "Per-window classification under two hold-out designs.", "tab:splits",
        "lcc",
        ["Metric", "Random (window-wise)", "Grouped (session-wise)"],
        split_rows,
        size="footnotesize", colsep_pt=4,
        notes="The positive class is input automation. The grouped split keeps "
              "every session entirely on one side, so no window is scored "
              "against its own session; its figures are the mean $\\pm$ one "
              "standard deviation over ten session-wise splits. "
              "Counts as TP/FP/FN/TN: "
              rf"random {r_rand['tp']}/{r_rand['fp']}/{r_rand['fn']}/{r_rand['tn']}; "
              rf"first grouped split {first['tp']}/{first['fp']}/{first['fn']}/{first['tn']}.",
    )

    # -- Table III: features and importance ---------------------------------
    forest = ml._make_model()
    forest.fit(data[ml.FEATURES].values, data["label"].values)
    importance = dict(zip(ml.FEATURES, forest.feature_importances_))
    numbers["feature_importance"] = {k: float(v) for k, v in importance.items()}

    # Permutation importance on the held-out side of the first grouped split,
    # F1-scored, because mean decrease in impurity is biased toward continuous
    # features and is computed on training data.
    te_mask = matched_partition(data)
    Xa, ya = data[ml.FEATURES].values, data["label"].values
    perm_model = ml._make_model()
    perm_model.fit(Xa[~te_mask], ya[~te_mask])
    perm = permutation_importance(
        perm_model, Xa[te_mask], ya[te_mask],
        n_repeats=20, random_state=SEED, scoring="f1",
    )
    perm_importance = dict(zip(ml.FEATURES, perm.importances_mean))
    numbers["permutation_importance"] = {
        k: float(v) for k, v in perm_importance.items()
    }

    descriptions = {
        "key_diversity": "distinct keys per keystroke",
        "ks_iei_cv": "CV of inter-keystroke intervals",
        "move_iei_cv": "CV of inter-move intervals",
        "iei_cv": "CV of all inter-event intervals",
        "step_mean": "mean pointer step, pixels",
        "step_cv": "CV of pointer step size",
        "mouse_fraction": "mouse events per event",
    }
    feat_rows = [
        [rf"\texttt{{{esc(f)}}}", descriptions[f],
         f"{importance[f]:.3f}", f"{perm_importance[f]:.3f}"]
        for f in sorted(ml.FEATURES, key=lambda f: -importance[f])
    ]
    write_table(
        "features", "Per-window shape features, ranked by importance.",
        "tab:features", "llrr",
        ["Feature", "Definition", "MDI", "Perm."], feat_rows,
        size="footnotesize", colsep_pt=3,
        notes="MDI is mean decrease in impurity over the forest fitted to all "
              "windows; Perm.\\ is $F_1$-scored permutation importance on the "
              "held-out side of the first session-wise split (20 shuffles). "
              "CV denotes the coefficient of variation.",
    )

    # -- Table VI: model and feature-set comparison -------------------------
    print("Comparing models and feature blocks...")
    model_factories = {
        "Majority class": lambda: DummyClassifier(strategy="most_frequent"),
        "Logistic regression": lambda: make_pipeline(
            StandardScaler(), LogisticRegression(max_iter=2000,
                                                 class_weight="balanced")),
        "Decision tree (depth 3)": lambda: DecisionTreeClassifier(
            max_depth=3, class_weight="balanced", random_state=SEED),
        "Random forest (proposed)": lambda: ml._make_model(),
    }
    model_rows, model_numbers = [], {}
    for name, factory in model_factories.items():
        r = evaluate_repeated(data, factory, ml.FEATURES)
        model_numbers[name] = r
        model_rows.append([
            name, f"{r['accuracy']['mean']:.3f}", f"{r['precision']['mean']:.3f}",
            f"{r['recall']['mean']:.3f}", fmt_pm(r["f1"]),
            f"{r['roc_auc']['mean']:.4f}",
        ])

    blocks = {
        "Timing only": ["ks_iei_cv", "move_iei_cv", "iei_cv"],
        "Geometry only": ["step_mean", "step_cv"],
        "Keyboard only": ["key_diversity", "ks_iei_cv"],
        "Mouse only": ["move_iei_cv", "step_mean", "step_cv", "mouse_fraction"],
        "All seven": ml.FEATURES,
    }
    block_rows, block_numbers = [], {}
    for name, feats in blocks.items():
        r = evaluate_repeated(data, lambda: ml._make_model(), feats)
        block_numbers[name] = r
        block_rows.append([
            f"{name} ({len(feats)})", f"{r['accuracy']['mean']:.3f}",
            f"{r['precision']['mean']:.3f}", f"{r['recall']['mean']:.3f}",
            fmt_pm(r["f1"]), f"{r['roc_auc']['mean']:.4f}",
        ])
    numbers["models"] = model_numbers
    numbers["blocks"] = block_numbers

    write_table(
        "ablation",
        "Classifier and feature-block comparison, session-wise hold-out.",
        "tab:ablation", "lccccc",
        ["Configuration", "Acc.", "Prec.", "Rec.", r"$F_1$", "AUC"],
        model_rows + [[r"\midrule \emph{Feature blocks}", "", "", "", "", ""]]
        + block_rows,
        size="scriptsize", colsep_pt=3,
        notes="All feature-block rows use the proposed forest, varying only the "
              "inputs. Every figure is the mean over ten session-wise splits; "
              "$F_1$ carries $\\pm$ one standard deviation.",
    )

    # -- Leave-one-kind-out generalisation, matched genuine partition -------
    print("Leave-one-kind-out evaluation...")
    kind_of = kind_of_sessions(data)
    kind_arr = np.array([kind_of.get(s, "") for s in data["session"].values])
    y_all = data["label"].values
    X_all = data[ml.FEATURES].values
    genuine_train = ~te_mask & (y_all == 0)
    genuine_test = te_mask & (y_all == 0)
    ck_rows, ck_numbers, roc_data = [], {}, {}
    for kind in botgen.KINDS:
        kmask = kind_arr == kind
        train = genuine_train | ((y_all == 1) & ~kmask)
        test = genuine_test | kmask
        model = ml._make_model()
        model.fit(X_all[train], y_all[train])
        proba = model.predict_proba(X_all[test])[:, 1]
        r = score(y_all[test], model.predict(X_all[test]), proba)
        ck_numbers[kind] = r
        fpr, tpr, _ = roc_curve(y_all[test], proba)
        fpr, tpr = downsample_curve(fpr, tpr)
        roc_data[kind] = (fpr, tpr, r["roc_auc"])
        ck_rows.append([
            rf"\texttt{{{esc(kind)}}}", fmt(r["n_test"]),
            fmt(r["tp"] + r["fn"]), f"{r['precision']:.3f}",
            f"{r['recall']:.3f}", f"{r['f1']:.3f}", f"{r['roc_auc']:.4f}",
        ])
    ck_mean_f1 = float(np.mean([r["f1"] for r in ck_numbers.values()]))
    numbers["crosskind"] = {"folds": ck_numbers, "mean_f1": ck_mean_f1}
    write_table(
        "crosskind",
        "Generalisation to an automation kind absent from training: each row "
        "holds out every session of one generator kind.",
        "tab:crosskind", "lrrcccc",
        ["Held-out kind", "Windows", "Pos.", "Prec.", "Rec.",
         r"$F_1$", "AUC"],
        ck_rows,
        size="scriptsize", colsep_pt=3,
        notes=rf"Mean $F_1$ is {ck_mean_f1:.3f}. Training excludes all sessions "
              "of the held-out kind and all genuine sessions assigned to test; "
              "the genuine test partition is the first session-wise split of "
              r"Table~\ref{tab:splits}, so the folds are protocol-matched to "
              "the grouped row there.",
    )
    write_roc_figure(roc_data)

    # -- Class-conditional distributions and per-kind medians ---------------
    print("Feature distribution tables...")
    hum, syn = data[data.label == 0], data[data.label == 1]

    def pct_cells(sub, f):
        return [f"{np.percentile(sub[f], 5):.4f}", f"{sub[f].median():.4f}",
                f"{np.percentile(sub[f], 95):.4f}"]

    dist_rows = [[rf"\texttt{{{esc(f)}}}"] + pct_cells(hum, f) + pct_cells(syn, f)
                 for f in ml.FEATURES]
    write_table(
        "classdist",
        "Class-conditional feature distributions over the scored one-minute "
        "windows.",
        "tab:classdist", "lrrrrrr",
        ["Feature", "p05", "Median", "p95", "p05", "Median", "p95"],
        dist_rows,
        size="scriptsize", colsep_pt=3,
        pre_header=(r"& \multicolumn{3}{c}{Human} & "
                    r"\multicolumn{3}{c}{Automation} \\"
                    "\n" r"\cmidrule(lr){2-4} \cmidrule(lr){5-7}"),
        notes=rf"Percentiles over {fmt(len(hum))} genuine and {fmt(len(syn))} "
              "synthetic windows.",
    )

    kf_rows = [["genuine"] + [f"{hum[f].median():.3f}" for f in ml.FEATURES]]
    kind_window_counts = {}
    for kind in botgen.KINDS:
        sub = data[(data.label == 1) & (kind_arr == kind)]
        kind_window_counts[kind] = len(sub)
        kf_rows.append([rf"\texttt{{{esc(kind)}}}"]
                       + [f"{sub[f].median():.3f}" for f in ml.FEATURES])
    numbers["kind_windows"] = kind_window_counts
    write_table(
        "kindfeatures",
        "Per-kind feature medians over the one-minute windows of each "
        "generator kind and of the genuine class.",
        "tab:kindfeatures",
        "l" + "r" * len(ml.FEATURES),
        ["Kind"] + [rf"\texttt{{{esc(f)}}}" for f in ml.FEATURES],
        kf_rows,
        size="footnotesize", star=True,
        notes="Medians over "
              + ", ".join(rf"{v} \texttt{{{esc(k)}}}"
                          for k, v in kind_window_counts.items())
              + rf" windows, and over the {fmt(len(hum))} genuine windows.",
    )

    # The one-feature rule the manuscript quotes: flag a window when step_cv
    # is exactly zero. No training, no other feature.
    zero_syn = float((syn["step_cv"] == 0).mean())
    zero_hum = float((hum["step_cv"] == 0).mean())
    rule_pred = (data["step_cv"] == 0).astype(int).values
    numbers["stepcv_rule"] = {
        "zero_share_synthetic": zero_syn,
        "zero_share_human": zero_hum,
        **{k: v for k, v in score(y_all, rule_pred,
                                  rule_pred.astype(float)).items()
           if k in ("accuracy", "precision", "recall", "f1")},
    }

    # -- Table VII: day-level policy sensitivity ----------------------------
    print("Sweeping the day-level decision policy...")
    all_events = events_io.load_events()
    all_events["day"] = pd.to_datetime(all_events["event_time"]).dt.date
    archive = all_events[all_events["day"] <= FREEZE].copy()

    # The decision unit is (user, day), matching keyspark.ml.score_days. Grouping
    # by day alone would let the test user's injected events contaminate the
    # genuine user's own record for that date.
    seeded = {dt.date.fromisoformat(d) for d in events_io.HUMAN_EXCLUDE_DAYS}
    archive["is_bot"] = archive["day"].isin(seeded) | archive["user"].isin(
        events_io.HUMAN_EXCLUDE_USERS
    )
    genuine_mask = ~archive["is_bot"]

    # Genuine days are scored OUT OF FOLD: every window is scored by a forest
    # that never saw its session. Scoring them with the full model would report
    # a training-set false-alarm rate, which is meaningless. The seeded days and
    # the test user are absent from training entirely, so the full model scores
    # them without leakage.
    oof = oof_probabilities(data)
    genuine_scored = windows_with_sessions(archive[genuine_mask], "H")
    genuine_scored = genuine_scored.merge(
        oof, on=["user", "window_start"], how="left"
    )
    genuine_scored["proba"] = genuine_scored["proba"].fillna(0.0)

    bot_scored = ml._window_features(archive[~genuine_mask])
    bot_scored["proba"] = forest.predict_proba(bot_scored[ml.FEATURES].values)[:, 1]

    scored = pd.concat([genuine_scored, bot_scored], ignore_index=True)
    scored["day"] = pd.to_datetime(scored["window_start"]).dt.date
    truth = archive.groupby(["user", "day"])["is_bot"].max()

    thresholds = (0.5, 0.6, 0.7, 0.8, 0.9, 0.95)
    min_windows = (1, 2, 3, 5)
    sweep_numbers = []
    for thresh in thresholds:
        for min_w in min_windows:
            flagged = (
                scored[scored["proba"] >= thresh].groupby(["user", "day"]).size()
            )
            decision = flagged.reindex(truth.index).fillna(0) >= min_w
            tp = int((decision & truth).sum())
            fp = int((decision & ~truth).sum())
            fn = int((~decision & truth).sum())
            tn = int((~decision & ~truth).sum())
            fpr = fp / max(fp + tn, 1)
            fnr = fn / max(fn + tp, 1)
            rec = {"threshold": thresh, "min_windows": min_w, "tp": tp,
                   "fp": fp, "fn": fn, "tn": tn, "fpr": fpr, "fnr": fnr}
            sweep_numbers.append(rec)
    numbers["day_policy"] = sweep_numbers
    numbers["day_truth"] = {
        "automation_days": int(truth.sum()),
        "human_days": int((~truth).sum()),
    }

    # Recommended operating point: no false alarms first, then fewest misses,
    # then the smallest window requirement (a day flags sooner), then the lowest
    # probability threshold that still achieves it.
    clean = [r for r in sweep_numbers if r["fp"] == 0]
    best = min(clean or sweep_numbers,
               key=lambda r: (r["fnr"], r["fpr"], r["min_windows"], r["threshold"]))
    numbers["day_policy_best"] = best
    numbers["day_policy_shipped"] = next(
        r for r in sweep_numbers
        if r["threshold"] == ml.WINDOW_THRESHOLD
        and r["min_windows"] == ml.MIN_FLAG_WINDOWS
    )

    # Name the automation day the recommended policy still misses, so the paper
    # can say which case is hard rather than only quoting a rate.
    flagged_best = (
        scored[scored["proba"] >= best["threshold"]].groupby(["user", "day"]).size()
    )
    decided = flagged_best.reindex(truth.index).fillna(0) >= best["min_windows"]
    missed = truth.index[truth.values & ~decided.values].tolist()
    window_counts = scored.groupby(["user", "day"]).size()
    numbers["day_policy_missed"] = [
        {"user": u, "day": str(d), "windows": int(window_counts.get((u, d), 0))}
        for u, d in missed
    ]

    # Presented as a threshold-by-window matrix: 24 rows of mostly repeated
    # values compress to 6, and the shape of the trade-off becomes visible.
    by_cell = {(r["threshold"], r["min_windows"]): r for r in sweep_numbers}
    matrix_rows = []
    for thresh in thresholds:
        cells = []
        for min_w in min_windows:
            r = by_cell[(thresh, min_w)]
            cell = f"{r['fp']}"
            if (thresh, min_w) == (ml.WINDOW_THRESHOLD, ml.MIN_FLAG_WINDOWS):
                cell = rf"\underline{{{cell}}}"
            if (thresh, min_w) == (best["threshold"], best["min_windows"]):
                cell = rf"\textbf{{{cell}}}"
            cells.append(cell)
        detected = {by_cell[(thresh, m)]["tp"] for m in min_windows}
        label = (str(next(iter(detected))) if len(detected) == 1
                 else f"{min(detected)}--{max(detected)}")
        matrix_rows.append([f"{thresh:.2f}"] + cells + [label])
    write_table(
        "daypolicy",
        "False alarms by decision threshold and sustained-window requirement.",
        "tab:daypolicy", "c" + "c" * len(min_windows) + "c",
        [r"$\tau$"] + [rf"$m={m}$" for m in min_windows] + ["Detected"],
        matrix_rows,
        notes=rf"A day is flagged when at least $m$ of its windows score "
              rf"$\geq \tau$. Cells give false alarms out of "
              rf"{int((~truth).sum())} genuine days; the last column gives "
              rf"detections out of {int(truth.sum())} automation days. "
              rf"Underlined is the released "
              rf"configuration, bold the zero-false-alarm alternative "
              rf"discussed in the text. No day in this "
              rf"evaluation appears in training.",
    )

    # -- Table IV and the micro-batch sweep --------------------------------
    write_performance_tables(numbers)

    with open(os.path.join(OUT_DIR, "numbers.json"), "w") as fh:
        json.dump(numbers, fh, indent=2, default=str)
    print(f"  wrote {OUT_DIR}/numbers.json")

    print("\nHeadline numbers")
    print(f"  corpus           {numbers['dataset']['events']:,} events, "
          f"{numbers['dataset']['days']} days, "
          f"{numbers['dataset']['sessions']} sessions")
    print(f"  class balance    human {len(human):,} / automation {len(synth):,} "
          f"windows ({human['session'].nunique()} / "
          f"{synth['session'].nunique()} sessions)")
    print(f"  Random (window-wise)     acc {r_rand['accuracy']:.3f}  "
          f"F1 {r_rand['f1']:.3f}  AUC {r_rand['roc_auc']:.4f}")
    print(f"  Grouped (session-wise)   acc {rep['accuracy']['mean']:.3f}  "
          f"F1 {rep['f1']['mean']:.3f} +- {rep['f1']['std']:.3f}  "
          f"AUC {rep['roc_auc']['mean']:.4f}")
    print(f"  Cross-kind mean F1       {ck_mean_f1:.3f}  "
          + "  ".join(f"{k} {r['f1']:.3f}" for k, r in ck_numbers.items()))
    print(f"  shipped policy   tau={ml.WINDOW_THRESHOLD} m={ml.MIN_FLAG_WINDOWS}"
          f"  FPR {numbers['day_policy_shipped']['fpr'] * 100:.1f}%"
          f"  FNR {numbers['day_policy_shipped']['fnr'] * 100:.1f}%")
    print(f"  best policy      tau={best['threshold']} m={best['min_windows']}"
          f"  FPR {best['fpr'] * 100:.1f}%  FNR {best['fnr'] * 100:.1f}%")


if __name__ == "__main__":
    main()
