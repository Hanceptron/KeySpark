def score(y_true, y_pred, proba) -> dict:
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
        "f1": f1_score(y_true, y_pred, zero_division=0),
        "roc_auc": roc_auc_score(y_true, proba) if len(set(y_true)) > 1 else None,
        "tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
        "n_test": int(len(y_true)),
    }


def evaluate(df: pd.DataFrame, model, features: list[str], grouped: bool) -> dict:
    """Fit and score under either a random or a session-wise hold-out."""
    X, y, g = df[features].values, df["label"].values, df["session"].values
    if grouped:
        splitter = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=SEED)
        tr, te = next(splitter.split(X, y, groups=g))
    else:
        tr, te = train_test_split(
            np.arange(len(y)), test_size=0.25, stratify=y, random_state=SEED
        )
    model.fit(X[tr], y[tr])
    proba = model.predict_proba(X[te])[:, 1]
    out = score(y[te], model.predict(X[te]), proba)
    out["n_train"] = int(len(tr))
    return out


def evaluate_repeated(df: pd.DataFrame, model_factory, features: list[str],
                      n_repeats: int = 10) -> dict:
    """Session-wise hold-out repeated over ``n_repeats`` group shuffles.

    The first split reproduces the single-split partition (same seed), so the
    confusion counts of the first run are the ones a single-split evaluation
    would have reported. Returns mean and standard deviation per metric.
    """
    X, y, g = df[features].values, df["label"].values, df["session"].values
    splitter = GroupShuffleSplit(n_splits=n_repeats, test_size=0.25,
                                 random_state=SEED)
    runs = []
    for tr, te in splitter.split(X, y, groups=g):
        model = model_factory()
        model.fit(X[tr], y[tr])
        proba = model.predict_proba(X[te])[:, 1]
        runs.append(score(y[te], model.predict(X[te]), proba))
    agg: dict = {}
    for k in ("accuracy", "precision", "recall", "f1"):
        vals = [r[k] for r in runs]
        agg[k] = {"mean": float(np.mean(vals)), "std": float(np.std(vals))}
    aucs = [r["roc_auc"] for r in runs if r["roc_auc"] is not None]
    agg["roc_auc"] = {"mean": float(np.mean(aucs)), "std": float(np.std(aucs))}
    agg["first"] = runs[0]
    agg["n_repeats"] = n_repeats
    return agg


def matched_partition(data: pd.DataFrame):
    """The exact session-wise partition of the grouped row of the splits table:
    first GroupShuffleSplit with the paper seed. Returns boolean test mask."""
    X, y, g = data[ml.FEATURES].values, data["label"].values, data["session"].values
    splitter = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=SEED)
    _, te = next(splitter.split(X, y, groups=g))
    te_mask = np.zeros(len(y), dtype=bool)
    te_mask[te] = True
    return te_mask


def kind_of_sessions(data: pd.DataFrame) -> dict:
    """Map each synthetic session id to its generator kind. The generator emits
    ``sessions_per_kind`` sessions per kind in KINDS order, separated by one-hour
    gaps, so the session cut of add_sessions recovers them in the same order."""
    synth_sessions = sorted(
        data.loc[data["label"] == 1, "session"].unique(),
        key=lambda s: int(s.split(":")[1]),
    )
    per_kind = len(synth_sessions) // len(botgen.KINDS)
    assert per_kind * len(botgen.KINDS) == len(synth_sessions), \
        "synthetic session count is not a multiple of the kind count"
    return {s: botgen.KINDS[i // per_kind] for i, s in enumerate(synth_sessions)}


def downsample_curve(fpr: np.ndarray, tpr: np.ndarray, limit: int = 120):
    if len(fpr) <= limit:
        return fpr, tpr
    idx = np.unique(np.linspace(0, len(fpr) - 1, limit).astype(int))
    return fpr[idx], tpr[idx]


