"""Regenerate every numeric table in the KeySpark paper from the live archive.

Emits LaTeX fragments into paper/tables/ plus numbers.json holding every value
the manuscript quotes, so the text and the artifacts can never drift apart. Run:

    .venv/bin/python paper/scripts/make_tables.py

Nothing here mutates the pipeline: the archive is read, models are trained in
memory, and only paper/tables/ is written. keyspark.ml is imported for its
featurizer and hyperparameters rather than reimplemented, so the paper describes
the code that actually ships.

Two corpora appear in the paper and they are deliberately different:

  * the performance benchmark (benchmark.py) replays the COMPLETE archive,
    because that is what the deployed pipeline processes;
  * the detection evaluation uses the GENUINE subset - the June freeze with the
    seeded demo days and the bot-test user removed, per keyspark.events_io.

Both counts are printed and both are stated in the manuscript.
"""

