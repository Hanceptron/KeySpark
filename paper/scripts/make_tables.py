# ---------------------------------------------------------------------------
# LaTeX helpers
# ---------------------------------------------------------------------------
def esc(text: str) -> str:
    return str(text).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def write_table(name: str, caption: str, label: str, spec: str,
                header: list[str], rows: list[list], notes: str = "",
                size: str = "", colsep_pt: int = 0, star: bool = False,
                pre_header: str = "") -> None:
    """Emit one IEEEtran table fragment. Caption goes above the tabular, per the
    style checklist. ``size`` ("footnotesize"/"scriptsize") and ``colsep_pt``
    shrink wide tables; ``star`` emits a two-column table* float."""
    env = "table*" if star else "table"
    lines = [
        "% generated by paper/scripts/make_tables.py -- do not edit by hand",
        rf"\begin{{{env}}}[t]",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        r"\centering",
    ]
    if size:
        lines.append(rf"\{size}")
    if colsep_pt:
        lines.append(rf"\setlength{{\tabcolsep}}{{{colsep_pt}pt}}")
    lines += [
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
    ]
    if pre_header:
        lines.append(pre_header)
    lines += [
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(str(c) for c in row) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    if notes:
        lines.append(rf"\\[2pt] \footnotesize {notes}")
    lines.append(rf"\end{{{env}}}")
    path = os.path.join(OUT_DIR, f"{name}.tex")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  wrote {path}")


def fmt(n: float, places: int = 0) -> str:
    return f"{n:,.{places}f}"


def fmt_pm(agg: dict, places: int = 3) -> str:
    """mean +- std cell from an aggregate produced by evaluate_repeated."""
    return rf"{agg['mean']:.{places}f} $\pm$ {agg['std']:.{places}f}"


