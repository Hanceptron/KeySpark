"""Table of processing performance and latency for the Sensors manuscript.

    .venv/bin/python paper/scripts/sensors_performance.py

Reads only JSON outputs already in paper/tables and writes
tables/performance_sensors.tex (label tab:performance):
- benchmark.json  (benchmark.py): batch throughput over the complete archive,
  three repetitions;
- kafkasweep.json (kafkabench.py sweep): streaming throughput at four files per
  micro-batch on the Parquet replay and on the deployed Kafka path, three runs;
- latency.json    (kafkabench.py latency): the specified bound and the measured
  probe latency.

performance.tex (make_tables.py) stays as it is for the IEEE paper; it lists a
65 s "end-to-end floor" that the latency probes contradict for key presses late
in a minute, so the Sensors manuscript uses this table instead.
"""
from __future__ import annotations

import json
import os

import numpy as np

TABLES = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tables")


def load(name: str) -> dict:
    with open(os.path.join(TABLES, name)) as fh:
        return json.load(fh)


def main() -> None:
    bench, sweep, lat = load("benchmark.json"), load("kafkasweep.json"), load("latency.json")
    batch = bench["batch"]["summary"]["throughput_events_per_sec"]
    par = {p["files_per_batch"]: p for p in sweep["parquet"]}[4]
    kaf = {p["files_per_batch"]: p for p in sweep["kafka"]}[4]
    d = lat["distribution_s"]
    close = np.array([p["latency_s"] + p["second_of_minute"] - 60 for p in lat["probes"]
                      if p["latency_s"] is not None])

    def rate(p):
        s = p["processed_rows_per_sec"]
        return f"{s['mean']:,.0f} rows/s", f"{s['min']:,.0f}--{s['max']:,.0f}"

    rows = [
        ["Batch analytics (full archive)", f"${batch['mean'] / 1e6:.2f} \\times 10^{{6}}$ ev/s",
         f"$\\pm$ ${batch['std'] / 1e6:.2f} \\times 10^{{6}}$"],
        ["Streaming, Parquet replay (4 files)", *rate(par)],
        [f"Streaming, Kafka path ({kaf['max_offsets_per_trigger']:,} rows)", *rate(kaf)],
        [r"\midrule Window close to emission (configuration)", "35--65 s", "watermark + 1--2 triggers"],
        ["Window close to emission (measured)", f"{np.median(close):.0f} s",
         f"{close.min():.0f}--{close.max():.0f}"],
        [r"\textbf{Probe event to output (measured)}", rf"\textbf{{{d['median']:.0f} s}}",
         f"{d['min']:.0f}--{d['max']:.0f}"],
    ]
    notes = (
        f"Batch: mean $\\pm$ standard deviation of {len(batch['runs'])} repetitions over the complete "
        f"{bench['batch']['summary']['events']['mean']:,}-event archive. Streaming: processed rows per "
        f"second (input rows divided by Spark's \\texttt{{triggerExecution}} time), mean and range of "
        f"{sweep['runs_per_point']} runs at four files, or the same number of rows, per micro-batch "
        f"(Table~\\ref{{tab:kafkasweep}}). Latency: median and range over {lat['n_seen']} probe events "
        f"(Table~\\ref{{tab:latency}}). The configuration uses one-minute windows, a 5~s watermark, and a 30~s metrics trigger. Probe events are written to the Kafka topic with the agent's producer "
        f"settings and timed to their window's first appearance in the metrics Parquet output. Window plus "
        f"watermark alone ({lat['spec_bound_s']}~s) applies only to an event at the start of a minute and leaves "
        f"out the trigger."
    )
    lines = [
        "% generated by paper/scripts/sensors_performance.py -- do not edit by hand",
        r"\begin{table}[H]",
        r"\caption{Processing performance and latency from the Kafka topic to the per-minute output.}",
        r"\label{tab:performance}",
        r"\centering",
        r"\small",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Measure & Value & Variation \\",
        r"\midrule",
        *[" & ".join(r) + r" \\" for r in rows],
        r"\bottomrule",
        r"\end{tabular}",
        rf"\\[2pt] \footnotesize {notes}",
        r"\end{table}",
    ]
    with open(os.path.join(TABLES, "performance_sensors.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", os.path.join(TABLES, "performance_sensors.tex"))


if __name__ == "__main__":
    main()
