"""Plot one genuine day of the corpus (the freeze day, 18 June 2026) from the
event archive, replacing the dashboard screenshot in the manuscript. Counts
only: key presses, clicks, and pointer events per five-minute bin, host-local
time. No key identity or coordinate is used.

    .venv/bin/python paper/scripts/dayplot.py
"""

import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.getcwd())
from keyspark import events_io  # noqa: E402

DAY = "2026-06-18"
BIN_MIN = 5
OUT = "paper/figures/dayplot.tex"


def main() -> None:
    ev = events_io.exclude_nonhuman(events_io.load_events())
    ev["local_day"] = events_io.local_day(ev["event_time"]).to_numpy()
    ev = ev[ev["local_day"] == DAY].copy()
    # Same host-local conversion as events_io.local_day, which the dashboard uses.
    from datetime import datetime, timezone
    t = pd.to_datetime(ev["event_time"]).dt.tz_localize("UTC").dt.tz_convert(
        datetime.now(timezone.utc).astimezone().tzinfo
    )
    ev["hour"] = t.dt.hour + t.dt.minute / 60.0
    ev["bin"] = (np.floor(ev["hour"] * 60 / BIN_MIN) * BIN_MIN / 60.0).round(4)
    bins = np.round(np.arange(0, 24, BIN_MIN / 60.0), 4)

    def counts(mask) -> pd.Series:
        return ev[mask].groupby("bin").size().reindex(bins, fill_value=0)

    keys = counts(ev["type"] == "key_down")
    clicks = counts(ev["type"] == "click")
    pointer = counts(ev["type"].isin(["move", "click", "scroll"]))

    def coords(s: pd.Series) -> str:
        return " ".join(f"({h:.3f},{int(v)})" for h, v in s.items())

    body = rf"""% generated by paper/scripts/dayplot.py -- do not edit by hand
\begin{{figure}}[t]
\centering
\begin{{tikzpicture}}
\begin{{axis}}[
  name=top, width=0.82\linewidth, height=3.6cm, scale only axis,
  xmin=0, xmax=24, xtick={{0,3,6,9,12,15,18,21,24}}, xticklabels={{}},
  ymin=0, ylabel={{Events per {BIN_MIN}\,min}}, grid=major,
  legend pos=north west, legend cell align=left, legend style={{font=\footnotesize}},
]
\addplot[const plot, thick, color=blue] coordinates {{{coords(keys)}}};
\addlegendentry{{Key presses}}
\addplot[const plot, thick, dashed, color=orange] coordinates {{{coords(clicks)}}};
\addlegendentry{{Clicks}}
\end{{axis}}
\begin{{axis}}[
  at={{(top.south west)}}, anchor=north west, yshift=-0.35cm,
  width=0.82\linewidth, height=3.0cm, scale only axis,
  xmin=0, xmax=24, xtick={{0,3,6,9,12,15,18,21,24}},
  xlabel={{Local time (h), 18 June 2026}},
  ymin=0, ylabel={{Pointer events per {BIN_MIN}\,min}}, grid=major,
]
\addplot[const plot, thick, color=teal] coordinates {{{coords(pointer)}}};
\end{{axis}}
\end{{tikzpicture}}
\caption{{One day of the corpus (18 June 2026, the last day before the data
freeze), counted in {BIN_MIN}-minute bins. Upper panel: key presses and clicks;
lower panel: pointer events (moves, clicks, and scrolls). Activity arrives in
bursts separated by idle periods, the irregularity that the dispersion features
of Section~\ref{{sec:method}} measure.}}
\label{{fig:day}}
\end{{figure}}
"""
    with open(OUT, "w") as fh:
        fh.write(body)
    print(f"  wrote {OUT}  ({len(ev)} events on {DAY})")


if __name__ == "__main__":
    main()
