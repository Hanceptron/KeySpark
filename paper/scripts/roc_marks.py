"""Marks the two operating points on the leave-one-kind-out ROC curves for the
Sensors manuscript:

    .venv/bin/python paper/scripts/roc_marks.py

Reads figures/roc_crosskind.tex (make_tables.py) and the per-kind recall and
false-positive rate of the fixed 0.5 threshold and the 1% genuine budget from
tables/reanalysis.json (reanalysis_from_csv.py, the same leave-one-kind-out
folds). Writes figures/roc_crosskind_sensors.tex with circles for 0.5 and
triangles for the budget, in each curve's colour; zero false-positive rates are
clipped to 10^-3 as in the curves.
"""
from __future__ import annotations

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "figures", "roc_crosskind.tex")
OUT = os.path.join(ROOT, "figures", "roc_crosskind_sensors.tex")
COLOURS = {"jiggler": "blue", "typer": "red", "keep_awake": "teal", "clicker": "orange"}


def main() -> None:
    src = open(SRC).read()
    tt = json.load(open(os.path.join(ROOT, "tables", "reanalysis.json")))["threshold_transfer"]
    for k, c in COLOURS.items():  # the curve colours must match the legend order of the source
        entry = "\\addlegendentry{\\texttt{" + k.replace("_", "\\_") + "}"
        assert src.index(f"color={c}") < src.index(entry), k
    marks = []
    for pt, mark in (("fixed_0.5", "o"), ("budget_0.01", "triangle")):
        for k, c in COLOURS.items():
            v = tt[pt]["per_kind"][k]
            x = max(v["fpr"], 1e-3)
            marks.append(rf"\addplot[only marks, mark={mark}, mark size=2.6pt, color={c}, thick, forget plot] "
                         rf"coordinates {{({x:.4g},{v['recall']:.4f})}};")
    out = src.replace(r"\end{axis}", "\n".join(marks) + "\n" + r"\end{axis}", 1)
    out = out.replace("% generated by paper/scripts/make_tables.py -- do not edit by hand",
                      "% generated by paper/scripts/roc_marks.py from roc_crosskind.tex -- do not edit by hand")
    out = out.replace(r"\label{fig:roc}", r"\label{fig:roc}", 1)
    cap_end = "separability.}"
    assert cap_end in out
    out = out.replace(cap_end, "separability. Circles mark the fixed 0.5 threshold and triangles the 1\\%\n"
                               "genuine budget of Table~\\ref{tab:transfer}.}", 1)
    with open(OUT, "w") as fh:
        fh.write(out)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
